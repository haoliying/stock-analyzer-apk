 * 股票信息仓库 - 内置股票列表，支持拼音/名称/代码搜索
 */
class StockInfoRepository(private val context: Context) {

    private val prefs = context.getSharedPreferences("stock_info_cache", Context.MODE_PRIVATE)
    private val stockList: List<StockInfo> = buildStockList()

    fun searchStocks(query: String): List<StockInfo> {
        if (query.isBlank()) return emptyList()
        val q = query.trim().lowercase().replace(" ", "")
        return stockList.filter { info ->
            info.code.contains(q, ignoreCase = true) ||
            info.name.contains(query.trim()) ||
            info.pinyin.replace(" ", "").contains(q, ignoreCase = true)
        }.take(20)
    }

    fun searchByPinyin(pinyin: String): List<StockInfo> {
        if (pinyin.isBlank()) return emptyList()
        val q = pinyin.trim().lowercase().replace(" ", "")
        return stockList.filter { info ->
            info.pinyin.replace(" ", "").contains(q, ignoreCase = true) ||
            info.name.contains(pinyin) ||
            info.code.contains(q, ignoreCase = true)
        }.take(20)
    }

    fun getStockByCode(code: String): StockInfo? {
        return stockList.find { it.code == code }
    }

    /**
     * 根据纯数字代码推断完整代码（带sh/sz前缀）
     */
    fun guessFullCode(numericCode: String): String? {
        val q = numericCode.trim()
        return stockList.find { it.code.endsWith(q) }?.code
    }

